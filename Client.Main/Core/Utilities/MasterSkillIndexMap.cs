        /// <summary>Resolves the skill number for a tree index of the given character class (any family member).</summary>
        public static bool TryGetSkillNumber(byte characterClass, byte masterSkillIndex, out ushort skillNumber)
        {
            skillNumber = 0;
            return IndexToSkill.TryGetValue(ServerMasterSkills.ToMasterClass(characterClass), out var map)
                && map.TryGetValue(masterSkillIndex, out skillNumber);
        }
